using System.Text;
using System.Text.RegularExpressions;
using CommunityToolkit.Mvvm.ComponentModel;

namespace CS2Launcher.Models;

/// <summary>
/// Модель конфигурации CS2 (autoexec.cfg + настройки лаунчера).
/// </summary>
public class CS2Config : ObservableObject
{
    // Чувствительность с поддержкой десятых (0.1 — 10.0)
    private double _sensitivity = 2.0;
    private int _crosshairSize = 4;
    private int _crosshairThickness = 1;
    private int _crosshairGap = -1;
    private string _crosshairColor = "#00FF00";
    private bool _crosshairOutline = true;
    private bool _crosshairDot = false;
    private int _fov = 90;
    private int _viewmodelFov = 68;
    private bool _rawInput = true;
    private bool _noTutorial = true;
    private string _autoexecContent = string.Empty;
    private string _shareCode = string.Empty;

    /// <summary>Чувствительность мыши (0.1 — 10.0, с шагом 0.1).</summary>
    public double Sensitivity
    {
        get => _sensitivity;
        set => SetProperty(ref _sensitivity, Math.Round(Math.Clamp(value, 0.1, 10.0), 2));
    }

    public int CrosshairSize
    {
        get => _crosshairSize;
        set => SetProperty(ref _crosshairSize, Math.Clamp(value, 0, 10));
    }

    public int CrosshairThickness
    {
        get => _crosshairThickness;
        set => SetProperty(ref _crosshairThickness, Math.Clamp(value, 0, 5));
    }

    public int CrosshairGap
    {
        get => _crosshairGap;
        set => SetProperty(ref _crosshairGap, Math.Clamp(value, -10, 10));
    }

    public string CrosshairColor
    {
        get => _crosshairColor;
        set => SetProperty(ref _crosshairColor, value);
    }

    public bool CrosshairOutline
    {
        get => _crosshairOutline;
        set => SetProperty(ref _crosshairOutline, value);
    }

    public bool CrosshairDot
    {
        get => _crosshairDot;
        set => SetProperty(ref _crosshairDot, value);
    }

    public int Fov
    {
        get => _fov;
        set => SetProperty(ref _fov, Math.Clamp(value, 60, 120));
    }

    public int ViewmodelFov
    {
        get => _viewmodelFov;
        set => SetProperty(ref _viewmodelFov, Math.Clamp(value, 54, 68));
    }

    public bool RawInput
    {
        get => _rawInput;
        set => SetProperty(ref _rawInput, value);
    }

    public bool NoTutorial
    {
        get => _noTutorial;
        set => SetProperty(ref _noTutorial, value);
    }

    public string AutoexecContent
    {
        get => _autoexecContent;
        set => SetProperty(ref _autoexecContent, value);
    }

    /// <summary>Share-код прицела в формате CSGO-xxxxx-xxxxx-... (для импорта/экспорта).</summary>
    public string ShareCode
    {
        get => _shareCode;
        set => SetProperty(ref _shareCode, value);
    }

    /// <summary>
    /// Генерирует содержимое autoexec.cfg на основе настроек.
    /// </summary>
    public string GenerateAutoexec()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// ============================================");
        sb.AppendLine("// CS2 autoexec.cfg");
        sb.AppendLine("// Generated by CS2 Launcher");
        sb.AppendLine($"// Date: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine("// ============================================");
        sb.AppendLine();
        sb.AppendLine("// === Mouse settings ===");
        sb.AppendLine($"sensitivity {Sensitivity.ToString(System.Globalization.CultureInfo.InvariantCulture)}");
        sb.AppendLine($"m_rawinput {Convert.ToInt32(RawInput)}");
        sb.AppendLine();
        sb.AppendLine("// === Crosshair settings ===");
        sb.AppendLine($"cl_crosshairstyle 4");
        sb.AppendLine($"cl_crosshairsize {CrosshairSize}");
        sb.AppendLine($"cl_crosshairthickness {CrosshairThickness}");
        sb.AppendLine($"cl_crosshairgap {CrosshairGap}");
        sb.AppendLine($"cl_crosshair_drawoutline {Convert.ToInt32(CrosshairOutline)}");
        sb.AppendLine($"cl_crosshair_dot {Convert.ToInt32(CrosshairDot)}");
        sb.AppendLine($"cl_crosshaircolor {GetCrosshairColorIndex()}");
        sb.AppendLine($"cl_crosshaircolor_r {GetColorComponent(CrosshairColor, 'r')}");
        sb.AppendLine($"cl_crosshaircolor_g {GetColorComponent(CrosshairColor, 'g')}");
        sb.AppendLine($"cl_crosshaircolor_b {GetColorComponent(CrosshairColor, 'b')}");
        sb.AppendLine();
        sb.AppendLine("// === Viewmodel ===");
        sb.AppendLine($"viewmodel_fov {ViewmodelFov}");
        sb.AppendLine($"fov_cs_debug {Fov}");
        sb.AppendLine();
        sb.AppendLine("// === Misc ===");
        sb.AppendLine($"cl_disablehtmlmotd {Convert.ToInt32(NoTutorial)}");
        sb.AppendLine("host_writeconfig");

        return sb.ToString();
    }

    private int GetCrosshairColorIndex() => 5; // custom color

    private int GetColorComponent(string hex, char channel)
    {
        if (hex.StartsWith("#"))
            hex = hex.Substring(1);

        if (hex.Length != 6)
            return 255;

        return channel switch
        {
            'r' => Convert.ToInt32(hex.Substring(0, 2), 16),
            'g' => Convert.ToInt32(hex.Substring(2, 2), 16),
            'b' => Convert.ToInt32(hex.Substring(4, 2), 16),
            _ => 255
        };
    }

    // ============================================================
    // ИМПОРТ / ЭКСПОРТ КОНФИГОВ
    // ============================================================

    /// <summary>
    /// Парсит .cfg файл и применяет найденные настройки crosshair/мыши.
    /// </summary>
    public void ImportFromCfg(string cfgContent)
    {
        var lines = cfgContent.Split('\n', '\r', StringSplitOptions.RemoveEmptyEntries);

        foreach (var rawLine in lines)
        {
            var line = rawLine.Trim();
            if (line.StartsWith("//") || line.StartsWith("//"))
                continue;

            // Формат: команда значение (например "sensitivity 2.5")
            var match = Regex.Match(line, @"^\s*(\w+)\s+(\S+)");
            if (!match.Success)
                continue;

            var cmd = match.Groups[1].Value;
            var val = match.Groups[2].Value.Trim('"');

            try
            {
                switch (cmd)
                {
                    case "sensitivity":
                        if (double.TryParse(val, System.Globalization.NumberStyles.Any,
                            System.Globalization.CultureInfo.InvariantCulture, out var sens))
                            Sensitivity = sens;
                        break;

                    case "m_rawinput":
                        RawInput = val == "1";
                        break;

                    case "cl_crosshairsize":
                        if (int.TryParse(val, out var sz)) CrosshairSize = sz;
                        break;

                    case "cl_crosshairthickness":
                        if (int.TryParse(val, out var th)) CrosshairThickness = th;
                        break;

                    case "cl_crosshairgap":
                        if (int.TryParse(val, out var gap)) CrosshairGap = gap;
                        break;

                    case "cl_crosshair_drawoutline":
                        CrosshairOutline = val == "1";
                        break;

                    case "cl_crosshair_dot":
                        CrosshairDot = val == "1";
                        break;

                    case "cl_crosshaircolor_r":
                    case "cl_crosshaircolor_g":
                    case "cl_crosshaircolor_b":
                        UpdateCrosshairColor(cmd.Last(), val);
                        break;

                    case "viewmodel_fov":
                        if (int.TryParse(val, out var vf)) ViewmodelFov = vf;
                        break;

                    case "fov_cs_debug":
                        if (int.TryParse(val, out var fov)) Fov = fov;
                        break;

                    case "cl_disablehtmlmotd":
                        NoTutorial = val == "1";
                        break;
                }
            }
            catch { /* skip invalid lines */ }
        }
    }

    private void UpdateCrosshairColor(char channel, string value)
    {
        if (!int.TryParse(value, out var c))
            return;

        var hex = CrosshairColor.StartsWith("#") ? CrosshairColor.Substring(1) : CrosshairColor;
        if (hex.Length != 6) hex = "00FF00";

        var r = Convert.ToInt32(hex.Substring(0, 2), 16);
        var g = Convert.ToInt32(hex.Substring(2, 2), 16);
        var b = Convert.ToInt32(hex.Substring(4, 2), 16);

        var clamped = Math.Clamp(c, 0, 255);
        if (channel == 'r') r = clamped;
        else if (channel == 'g') g = clamped;
        else if (channel == 'b') b = clamped;

        CrosshairColor = $"#{r:X2}{g:X2}{b:X2}";
    }

    // ============================================================
    // SHARE-КОДЫ (CSGO-xxxxx-xxxxx-xxxxx-xxxxx-xxxxx)
    // ============================================================

    /// <summary>
    /// Генерирует share-код прицела в формате CS2 (упрощённая версия).
    /// Полный алгоритм кодирования сложный, здесь делаем читаемое представление.
    /// </summary>
    public string GenerateShareCode()
    {
        // Упрощённая схема: кодируем основные параметры в компактный код
        var data = new[]
        {
            CrosshairSize,
            CrosshairThickness,
            CrosshairGap + 10, // сдвиг чтобы было положительное
            Convert.ToInt32(CrosshairOutline),
            Convert.ToInt32(CrosshairDot),
            GetColorComponent(CrosshairColor, 'r'),
            GetColorComponent(CrosshairColor, 'g'),
            GetColorComponent(CrosshairColor, 'b')
        };

        // Кодируем в Base32-подобную строку
        var bytes = data.Select(d => (byte)d).ToArray();
        var code = Base32Encode(bytes);
        ShareCode = $"CSGO-{code.Substring(0, 5)}-{code.Substring(5, 5)}-{code.Substring(10, 5)}";
        return ShareCode;
    }

    /// <summary>
    /// Пытается распарсить share-код и применить настройки прицела.
    /// Возвращает true при успешном импорте.
    /// </summary>
    public bool ImportFromShareCode(string code)
    {
        try
        {
            // Нормализуем: убираем "CSGO-" и дефисы
            var clean = code.Trim().ToUpperInvariant();
            if (clean.StartsWith("CSGO-"))
                clean = clean.Substring(5);
            clean = clean.Replace("-", "");

            if (clean.Length < 15)
                return false;

            var bytes = Base32Decode(clean);
            if (bytes == null || bytes.Length < 8)
                return false;

            CrosshairSize = Math.Clamp((int)bytes[0], 0, 10);
            CrosshairThickness = Math.Clamp((int)bytes[1], 0, 5);
            CrosshairGap = Math.Clamp((int)bytes[2] - 10, -10, 10);
            CrosshairOutline = bytes[3] != 0;
            CrosshairDot = bytes[4] != 0;
            var r = Math.Clamp((int)bytes[5], 0, 255);
            var g = Math.Clamp((int)bytes[6], 0, 255);
            var b = Math.Clamp((int)bytes[7], 0, 255);
            CrosshairColor = $"#{r:X2}{g:X2}{b:X2}";

            ShareCode = code.Trim().ToUpperInvariant();
            return true;
        }
        catch
        {
            return false;
        }
    }

    // Простой Base32-кодер/декодер (алфавит CSGO без конфликтных символов)
    private const string Base32Alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

    private string Base32Encode(byte[] data)
    {
        var result = new StringBuilder();
        foreach (var b in data)
        {
            // Каждый байт = 2 символа Base32 (5 бит + 3 бита добиваем)
            int high = (b >> 3) & 0x1F;
            int low = (b << 2) & 0x1F;
            result.Append(Base32Alphabet[high]);
            result.Append(Base32Alphabet[low]);
        }
        // Дополняем до 15 символов
        while (result.Length < 15)
            result.Append('A');
        return result.ToString();
    }

    private byte[]? Base32Decode(string s)
    {
        var result = new List<byte>();
        for (int i = 0; i + 1 < s.Length; i += 2)
        {
            int high = Base32Alphabet.IndexOf(s[i]);
            int low = Base32Alphabet.IndexOf(s[i + 1]);
            if (high < 0 || low < 0)
                return null;
            byte b = (byte)(((high & 0x1F) << 3) | ((low & 0x1F) >> 2));
            result.Add(b);
        }
        return result.ToArray();
    }
}
